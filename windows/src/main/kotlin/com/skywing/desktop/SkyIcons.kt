/** Draws one of the app's icons in [tint]. */
@Composable
internal fun SkyIconView(icon: SkyIcon, tint: Color, modifier: Modifier = Modifier, size: Dp = 22.dp) {
    val path = remember(icon) { PathParser().parsePathString(icon.path).toPath() }
    Canvas(modifier.size(size)) {
        val factor = this.size.minDimension / 24f
        scale(factor, factor, pivot = Offset.Zero) {
            drawPath(path, tint)
        }
    }
}

/**
 * The SkyWing mark (wing and play triangle), drawn from the same shapes as the Android launcher icon
 * and cropped into a round badge.
 */
@Composable
internal fun SkyMark(size: Dp = 40.dp, modifier: Modifier = Modifier) {
    val theme = LocalSkyTheme.current
    val shapes = remember {
        listOf(
            PathParser().parsePathString("M 45 28 C 45 22 51 21 56 24 L 84 46 C 89 50 89 56 84 60 L 56 82 C 51 86 45 83 45 77 Z").toPath(),
            PathParser().parsePathString("M 25 42 C 34 45 40 39 45 34 C 42 45 37 51 28 51 C 23 50 19 46 18 41 Z").toPath(),
            PathParser().parsePathString("M 24 53 C 33 55 40 49 45 43 C 43 54 37 62 28 61 C 23 60 20 57 19 52 Z").toPath(),
            PathParser().parsePathString("M 28 64 C 35 66 42 61 46 55 C 46 65 41 72 35 72 C 30 72 25 69 23 63 Z").toPath(),
        )
    }
    val backdrop = if (theme.light) {
        listOf(Color(0xFFF8FBFF), Color(0xFFD9F3FF), Color(0xFFEAE4FF))
    } else {
        listOf(Color(0xFF12356A), Color(0xFF08132F), Color(0xFF25134F))
    }
    Box(modifier.size(size).clip(CircleShape).background(Brush.linearGradient(backdrop))) {
        Canvas(Modifier.size(size)) {
            val unit = this.size.minDimension / 108f
            val middle = Offset(this.size.width / 2f, this.size.height / 2f)
            scale(1.32f, 1.32f, pivot = middle) {
                scale(unit, unit, pivot = Offset.Zero) {
                    drawPath(
                        shapes[0],
                        Brush.linearGradient(
                            0f to Color(0xFF6BEEFF),
                            0.45f to Color(0xFF16A7FD),
                            0.76f to Color(0xFF1754F3),
                            1f to Color(0xFF943FF3),
                            start = Offset(45f, 24f),
                            end = Offset(82f, 78f),
                        ),
                    )
                    drawPath(shapes[1], Color(0xFF60E8FF))
                    drawPath(shapes[2], Color(0xFF26BFFC))
                    drawPath(shapes[3], Color(0xFF1976E9))
                }
            }
        }
    }
}
